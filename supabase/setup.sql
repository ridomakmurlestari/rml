create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

-- Hapus fungsi/tabel pilot lama yang bergantung pada auth.users.
drop function if exists public.lookup_login_email(text) cascade;
drop function if exists public.is_admin() cascade;
drop table if exists public.area_assignments cascade;
drop table if exists public.visits cascade;
drop table if exists public.profiles cascade;

drop table if exists public.app_sessions cascade;
drop table if exists public.app_users cascade;

create table public.app_users (
  id uuid primary key default gen_random_uuid(),
  account_key text unique not null,
  login_name text unique not null,
  display_name text not null,
  phone text unique not null,
  password_hash text not null,
  role text not null check (role in ('admin','sales')),
  must_change_password boolean not null default true,
  active boolean not null default true,
  can_switch_area_freely boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.app_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.app_users(id) on delete cascade,
  token_hash text unique not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  last_used_at timestamptz not null default now()
);
create index app_sessions_user_idx on public.app_sessions(user_id);
create index app_sessions_expiry_idx on public.app_sessions(expires_at);

create table public.visits (
  id text primary key,
  user_id uuid not null references public.app_users(id) on delete cascade,
  sales_email text not null default '',
  sales_name text not null default '',
  customer_no text not null default '',
  customer_code text not null default '',
  customer_name text not null default '',
  area text not null default '',
  status text not null default '',
  visit_type text not null default 'Kunjungan Area',
  check_in_at timestamptz,
  check_out_at timestamptz,
  updated_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb
);
create index visits_user_id_idx on public.visits(user_id);
create index visits_check_out_at_idx on public.visits(check_out_at desc);
create index visits_area_idx on public.visits(area);

create table public.area_assignments (
  id bigint generated by default as identity primary key,
  sales_email text not null,
  area text not null,
  created_at timestamptz not null default now(),
  unique(sales_email, area)
);

